# 전용 파서가 처리해 10배 가까이 빠르다(측정: 2.9초 → 0.26초).
def _js_literal(obj):
    """JSON 본문을 작은따옴표 문자열로 감싼다 — 큰따옴표를 escape하지 않아 크기가 늘지 않는다"""
    t = json.dumps(obj, ensure_ascii=False, separators=(",", ":"))
    t = t.replace("\\", "\\\\").replace("'", "\\'")
    t = t.replace("\u2028", "\\u2028").replace("\u2029", "\\u2029")   # JS에서 줄바꿈으로 취급되는 문자
    return "'" + t + "'"

