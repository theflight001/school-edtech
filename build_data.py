# 다른 시도에 같은 이름이 있을 수 있으니 후보가 딱 하나일 때만 인정한다.
_SIDO_PFX = ["서울", "부산", "대구", "인천", "광주", "대전", "울산", "세종",
             "경기", "강원", "충북", "충남", "전북", "전남", "경북", "경남", "제주"]
def scoped_alias(name, sido):
    """시도 한정 별칭 — (시도 앞 두 글자, 교명)으로 학교코드를 바로 찾는다. 없으면 None."""
    if not name or not sido:
        return None
    key = (sido2(sido), name)
    if key in ALIAS_SCOPED:
        return master_by_code.get(ALIAS_SCOPED[key])
    return None

_SIGUN = re.compile(r"([가-힣]{1,4}?)(시|군|구)(?=\s|$)")
def pick_by_title_place(cands, *texts):
    """같은 시도의 동명 학교를 계약명·수요기관에 적힌 시·군 이름으로 가른다.
    후보 주소에서 시·군 이름을 뽑아('경산시'→'경산') 본문에 그 지명이 있는 후보가 딱 하나일 때만 고른다."""
    body = " ".join(t for t in texts if t)
    if not body:
        return cands
    hit = []
    for c in cands:
        addr = c.get("address") or ""
        # 학교 이름에 든 지명은 증거가 아니다 — '오산초등학교' 계약은 어느 오산초든 '오산'이 들어 있어
        # 경기 오산시의 오산초로 쏠렸다(2026-09-15 구조검증 R01: 전남 오산초 25건·경남 금산초 9건)
        places = {m.group(1) for m in _SIGUN.finditer(addr)
                  if len(m.group(1)) >= 2 and m.group(1) not in (c.get("name") or "")}
        if any(pl in body for pl in places):
            hit.append(c)
    return hit if len(hit) == 1 else cands

def lookup_school(name):
    """교명 하나로 마스터에서 찾는다 — 정확 일치 → 띄어쓰기 무시 → 시도 접두어 가감"""
    nm = ALIAS.get(name, name)
    cands = master_by_name.get(nm, [])
    if cands:
        return cands
    cands = master_by_nkey.get(_nkey(nm), [])
    if len(cands) == 1:
        return cands
    alts = []
    for p in _SIDO_PFX:
        alts.append(p + nm)
        if nm.startswith(p):
            alts.append(nm[len(p):])
    hit = [c for a in alts for c in master_by_nkey.get(_nkey(a), [])]
    return hit if len(hit) == 1 else []

def find_school(name, region):
    cands = lookup_school(name)
    if len(cands) == 1:
        return cands[0]
    if len(cands) > 1:
        tok = region.split()[0] if region else ""
        pat = SIDO_PREFIX.get(tok)
        if pat:
            f = [c for c in cands if re.match(pat, c["sido"])]
            if len(f) == 1:
                return f[0]
    return None

