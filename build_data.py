def _nkey(n):
    # 가운뎃점은 표기가 넷이다: · (U+00B7) ㆍ (U+318D) ・ (U+30FB, NEIS 등재명) ‧ (U+2027)
    return re.sub(r"[\s·ㆍ・‧•∙\-_()（）]", "", n or "")
