def sido2(s):
    """시도 표기를 두 글자로 — '경상북도'·'경북'·'경상북도교육청' → '경북', '전남광주통합특별시(광주)' → '광주'"""
    s = s or ""
    if "(광주)" in s: return "광주"
    if "(전남)" in s: return "전남"
    for k, v in (("충청북", "충북"), ("충청남", "충남"), ("전라북", "전북"), ("전라남", "전남"),
                 ("경상북", "경북"), ("경상남", "경남")):
        if s.startswith(k): return v
    return s[:2]

