# 회사가 아닌 지출이 그렇다. 그대로 두면 '광희중학교의 다른 납품 보기'처럼
# 학교가 제 학교에 납품한 꼴이 되므로 업체로 보지 않는다.
def _same_org(a, b):
    f = lambda x: re.sub(r"[\s()·\-_.]|\(주\)|주식회사|㈜", "", x or "")
    return bool(f(a)) and f(a) == f(b)

